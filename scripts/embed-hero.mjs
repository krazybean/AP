// Regenerates src/hero-media.ts from a rendered hero video and its poster frame.
//
//   node scripts/embed-hero.mjs path/to/hero.mp4 path/to/poster.jpg
//
// The media is embedded in the server bundle on purpose: AP serves it itself, so the landing page works the
// same on every host and cannot lose its video to a missing static-file mapping. The file names carry a hash
// of the content, so they can be cached forever and a new render automatically gets a new URL.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const [videoFile, posterFile] = process.argv.slice(2);
if (!videoFile || !posterFile) {
  console.error("usage: node scripts/embed-hero.mjs <hero.mp4> <poster.jpg>");
  process.exit(1);
}

const video = readFileSync(videoFile);
const poster = readFileSync(posterFile);
if (video.subarray(4, 8).toString("latin1") !== "ftyp") throw new Error(`${videoFile} is not an MP4 file`);
if (poster[0] !== 0xff || poster[1] !== 0xd8) throw new Error(`${posterFile} is not a JPEG file`);

const hash = (buffer) => createHash("sha256").update(buffer).digest("hex").slice(0, 10);
const wrap = (buffer) => buffer.toString("base64").replace(/(.{120})/g, "$1\n");

writeFileSync(new URL("../src/hero-media.ts", import.meta.url), `// Generated by scripts/embed-hero.mjs. Do not edit by hand; see docs/HERO.md.
// video: ${video.length} bytes, poster: ${poster.length} bytes.

const VIDEO = \`
${wrap(video)}
\`;
const POSTER = \`
${wrap(poster)}
\`;

const decode = (text: string) => Buffer.from(text.replace(/\\s+/g, ""), "base64");

export const HERO_VIDEO = decode(VIDEO);
export const HERO_POSTER = decode(POSTER);
export const HERO_VIDEO_PATH = "/hero-${hash(video)}.mp4";
export const HERO_POSTER_PATH = "/hero-${hash(poster)}.jpg";
`);
console.log(`wrote src/hero-media.ts (${((video.length + poster.length) / 1024).toFixed(0)} KiB of media)`);
