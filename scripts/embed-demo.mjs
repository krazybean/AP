// Regenerates src/demo-assets.ts from a production build of the interactive demo.
//
//   (in the demo project)  npm run build           # vite build, base /demo-assets/, assetsDir ""
//   (in AP)                node scripts/embed-demo.mjs path/to/demo/dist
//
// Like the hero video, the demo is embedded in the server bundle so AP serves it itself and it works the same on
// every host. Files are stored gzipped (the script bundle is ~1.3 MB raw, ~380 KB gzipped) and served with
// `Content-Encoding: gzip` when the browser accepts it. Vite already puts a content hash in every file name.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

const dist = process.argv[2];
if (!dist) {
  console.error("usage: node scripts/embed-demo.mjs <demo dist directory>");
  process.exit(1);
}

const TYPES = { ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".woff2": "font/woff2", ".woff": "font/woff" };
const html = readFileSync(`${dist}/index.html`, "utf8");
if (!html.includes('src="/demo-assets/') || /https?:\/\//.test(html.replace(/<meta[^>]*>/g, ""))) throw new Error("index.html must reference only /demo-assets/ files; build with base '/demo-assets/'");

const wrap = (buffer) => buffer.toString("base64").replace(/(.{120})/g, "$1\n");
const files = readdirSync(dist).filter((name) => name !== "index.html").sort();
let total = 0;
const entries = files.map((name) => {
  const extension = name.slice(name.lastIndexOf("."));
  if (!TYPES[extension]) throw new Error(`unexpected file type in the demo build: ${name}`);
  if (!/-[A-Za-z0-9_-]{8}\.[a-z0-9]+$/.test(name)) throw new Error(`${name} has no content hash in its name`);
  const gz = gzipSync(readFileSync(`${dist}/${name}`), { level: 9 });
  total += gz.length;
  return `  ${JSON.stringify(`/demo-assets/${name}`)}: file(${JSON.stringify(TYPES[extension])}, \`\n${wrap(gz)}\n\`),`;
});

writeFileSync(new URL("../src/demo-assets.ts", import.meta.url), `// Generated by scripts/embed-demo.mjs. Do not edit by hand; see docs/HERO.md.
// ${files.length} files, ${(total / 1024).toFixed(0)} KiB gzipped.

export type DemoFile = { type: string; gzip: Buffer };

const file = (type: string, base64: string): DemoFile => ({ type, gzip: Buffer.from(base64.replace(/\\s+/g, ""), "base64") });

export const DEMO_HTML = ${JSON.stringify(html)};

export const DEMO_FILES: Record<string, DemoFile> = {
${entries.join("\n")}
};
`);
console.log(`wrote src/demo-assets.ts (${files.length} files, ${(total / 1024).toFixed(0)} KiB gzipped)`);
